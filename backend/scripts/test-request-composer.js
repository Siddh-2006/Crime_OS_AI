const { createApp } = require('../dist/app');
const { CaseChecklist } = require('../dist/modules/investigation/models/CaseChecklist.model');
const { DiaryEntry } = require('../dist/modules/investigation/models/DiaryEntry.model');
const { CaseEntity } = require('../dist/modules/investigation/models/CaseEntity.model');
const { Evidence } = require('../dist/modules/investigation/models/Evidence.model');
const { DepartmentRequest } = require('../dist/modules/investigation/models/DepartmentRequest.model');
const { AnalysisSnapshot } = require('../dist/modules/investigation/models/AnalysisSnapshot.model');
const { InvestigationOrchestrator } = require('../dist/modules/investigation/services/investigationOrchestrator');

// ─── Assertion helpers ────────────────────────────────────────────────────────
let passed = 0, failed = 0;
function assert(label, condition, detail = '') {
  if (condition) {
    console.log(`  ✅ ${label}`);
    passed++;
  } else {
    console.log(`  ❌ ${label}${detail ? ` — ${detail}` : ''}`);
    failed++;
  }
}

// ─── Seed Data ────────────────────────────────────────────────────────────────
const CASE_ID = new mongoose.Types.ObjectId();

async function seedFakeCase() {
  await CaseChecklist.create([
    { case_id: CASE_ID, sop_id: 'SOP_002', step_id: 'step_bank_kyc', title: 'Request Bank KYC from HDFC', status: 'pending', criticality: 'high', required_evidence: ['Bank Account Statement', 'KYC Documents'] },
    { case_id: CASE_ID, sop_id: 'SOP_002', step_id: 'step_inter_station', title: 'Request ground verification at suspect address', status: 'pending', criticality: 'medium', required_evidence: ['Verification Report'] }
  ]);
  
  await CaseEntity.create([
    { case_id: CASE_ID, entity_type: 'bank_account', value: '1234567890 (HDFC)', first_seen_entry_id: 'entry-1' },
    { case_id: CASE_ID, entity_type: 'suspect_address', value: 'Plot 42, Sector 9, Gandhinagar', first_seen_entry_id: 'entry-2' }
  ]);
}

async function runTest() {
  console.log("=== STARTING REQUEST COMPOSER E2E TEST ===");

  await connectDatabase();
  await seedFakeCase();
  console.log(`Seeded Case ID: ${CASE_ID.toString()}`);

  const app = createApp();
  const server = app.listen(0);
  const port = server.address().port;
  const baseUrl = `http://localhost:${port}/api/v1`;

  try {
    // --- SCENARIO 1: BANK KYC (External Department) ---
    console.log(`\n--- SCENARIO 1: BANK KYC ---`);
    console.log(`1. POST /cases/${CASE_ID}/requests/draft`);
    let draftRes = await axios.post(`${baseUrl}/cases/${CASE_ID}/requests/draft`, {
      step_id: 'step_bank_kyc',
      department_entity_id: 'HDFC Bank Nodal Officer',
      request_type: 'external_department',
      recipient_type: 'Bank'
    });
    
    assert("POST /draft returns 201 CREATED", draftRes.status === 201);
    assert("Draft has a request_id", !!draftRes.data.data.request_id);
    assert("Draft status is 'draft'", draftRes.data.data.status === 'draft');
    assert("Draft request_type is correct", draftRes.data.data.request_type === 'external_department');
    assert("Draft content was generated by LLM", typeof draftRes.data.data.draft_content === 'string' && draftRes.data.data.draft_content.length > 20);

    let reqId = draftRes.data.data.request_id;

    console.log(`\n2. PATCH /cases/requests/${reqId}`);
    let patchRes = await axios.patch(`${baseUrl}/cases/requests/${reqId}`, {
      draft_content: "Officer edited text: Please provide KYC urgently."
    });

    assert("PATCH /requests returns 200 OK", patchRes.status === 200);
    assert("Draft content was updated", patchRes.data.data.draft_content === "Officer edited text: Please provide KYC urgently.");

    console.log(`\n3. POST /cases/${CASE_ID}/requests/${reqId}/send`);
    let sendRes = await axios.post(`${baseUrl}/cases/${CASE_ID}/requests/${reqId}/send`);
    
    assert("POST /send returns 200 OK", sendRes.status === 200);
    assert("Request status is now 'sent'", sendRes.data.data.status === 'sent');

    // DB Assertions
    let checklist = await CaseChecklist.findOne({ case_id: CASE_ID, step_id: 'step_bank_kyc' });
    assert("Checklist step is marked 'in_progress'", checklist.status === 'in_progress');
    assert("Checklist step is locked by the request_id", checklist.locked_by_request_id === reqId);

    let diaryEntries = await DiaryEntry.find({ case_id: CASE_ID, event_type: 'request_sent', 'payload.request_id': reqId });
    assert("A diary_entry(request_sent) was successfully appended", diaryEntries.length === 1);

    // --- NEW: DEPARTMENT PORTAL INGESTION TEST ---
    console.log(`\n4. POST /department-portal/login (Mock Auth)`);
    let loginRes = await axios.post(`${baseUrl}/department-portal/login`, {
      username: 'hdfc',
      password: 'admin'
    });
    assert("POST /login returns 200 OK", loginRes.status === 200);
    assert("Login returns correct entity ID", loginRes.data.data.department_entity_id === 'HDFC Bank Nodal Officer');

    console.log(`\n5. GET /department-portal/requests`);
    let portalReqsRes = await axios.get(`${baseUrl}/department-portal/requests`, {
      params: { department_entity_id: 'HDFC Bank Nodal Officer' }
    });
    assert("GET /requests returns 200 OK", portalReqsRes.status === 200);
    assert("Found the pending bank KYC request", portalReqsRes.data.data.some(r => r.request_id === reqId));

    console.log(`\n6. POST /department-portal/requests/${reqId}/respond`);
    let respondRes = await axios.post(`${baseUrl}/department-portal/requests/${reqId}/respond`, {
      response_content: "MOCK RESPONSE: Here is the Bank KYC data."
    });
    assert("POST /respond returns 200 OK", respondRes.status === 200);

    // Final DB Assertions for Ingestion
    let finalRequest = await DepartmentRequest.findOne({ request_id: reqId });
    assert("Request status updated to response_received", finalRequest.status === 'response_received');

    let ingestedEvidence = await Evidence.findOne({ case_id: CASE_ID, type: 'document', linked_request_id: reqId });
    assert("Evidence document was successfully created from response", !!ingestedEvidence);
    assert("Evidence contains correct tags", ingestedEvidence.ai_tags.includes('department_response'));

    checklist = await CaseChecklist.findOne({ case_id: CASE_ID, step_id: 'step_bank_kyc' });
    assert("Checklist step is officially marked 'completed'", checklist.status === 'completed');
    assert("Checklist proof_evidence_ids includes the new evidence", checklist.proof_evidence_ids.includes(ingestedEvidence.evidence_id));

    let ingestionDiary = await DiaryEntry.find({ case_id: CASE_ID, event_type: 'response_received', 'payload.request_id': reqId });
    assert("A diary_entry(response_received) was successfully appended", ingestionDiary.length === 1);

    console.log(`\n7. Simulating BullMQ AnalysisWorker picking up the queued job...`);
    await InvestigationOrchestrator.runAnalysis(CASE_ID.toString());
    
    let latestSnapshot = await AnalysisSnapshot.findOne({ case_id: CASE_ID }).sort({ createdAt: -1 });
    assert("A new AnalysisSnapshot was successfully created by the Orchestrator", !!latestSnapshot);
    assert("The new snapshot's facts_used.checklist correctly shows step_bank_kyc as 'completed'", 
      latestSnapshot.facts_used.checklist.steps.some(s => s.step_id === 'step_bank_kyc' && s.status === 'completed')
    );

    // --- SCENARIO 2: INTER-STATION ASSIGNMENT ---
    console.log(`\n--- SCENARIO 2: INTER-STATION ASSIGNMENT ---`);
    console.log(`1. POST /cases/${CASE_ID}/requests/draft`);
    draftRes = await axios.post(`${baseUrl}/cases/${CASE_ID}/requests/draft`, {
      step_id: 'step_inter_station',
      department_entity_id: 'Gandhinagar Sector 7 Police Station',
      request_type: 'inter_station_assignment',
      recipient_type: 'Police Station'
    });
    
    assert("POST /draft returns 201 CREATED", draftRes.status === 201);
    assert("Draft status is 'draft'", draftRes.data.data.status === 'draft');
    assert("Draft request_type is correct", draftRes.data.data.request_type === 'inter_station_assignment');

    reqId = draftRes.data.data.request_id;

    console.log(`\n2. PATCH /cases/requests/${reqId}`);
    patchRes = await axios.patch(`${baseUrl}/cases/requests/${reqId}`, {
      draft_content: "Please check if suspect is at home."
    });
    assert("PATCH /requests returns 200 OK", patchRes.status === 200);

    console.log(`\n3. POST /cases/${CASE_ID}/requests/${reqId}/send`);
    sendRes = await axios.post(`${baseUrl}/cases/${CASE_ID}/requests/${reqId}/send`);
    assert("POST /send returns 200 OK", sendRes.status === 200);

    checklist = await CaseChecklist.findOne({ case_id: CASE_ID, step_id: 'step_inter_station' });
    assert("Checklist step is marked 'in_progress'", checklist.status === 'in_progress');
    assert("Checklist step is locked by the request_id", checklist.locked_by_request_id === reqId);

    diaryEntries = await DiaryEntry.find({ case_id: CASE_ID, event_type: 'request_sent', 'payload.request_id': reqId });
    assert("A diary_entry(request_sent) was successfully appended", diaryEntries.length === 1);

  } catch (err) {
    console.error("Test failed with error:");
    if (err.response) {
      console.error(err.response.data);
    } else {
      console.error(err);
    }
  } finally {
    console.log(`\nResults: ${passed} passed, ${failed} failed`);
    server.close();
    process.exit(failed > 0 ? 1 : 0);
  }
}

runTest().catch(console.error);
